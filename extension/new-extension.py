#!/usr/bin/env python3
"""Creates an XMQ extension project that builds and loads before a line of it is written.

An extension is a shared library the broker opens at start-up. It sees one header - the C ABI in
extension/xmq_extension.h - and links nothing of the broker, which is what lets it be built with
another compiler, kept closed, and shipped on its own schedule.

What this writes is a project with all of that already arranged: the CMake, the class, the entry
point, the configuration entry to paste, and a README. Every place where a decision belongs to you
is marked TODO and says what the choice is between. Build it as it comes out and the broker will
load it and log that it did - then start replacing the TODOs.

    ./new-extension.py audit-trail --capability observer
    ./new-extension.py device-auth --capability authenticator --database
    ./new-extension.py site-acl --capability authorizer --capability observer

Run with --help for the rest.
"""

