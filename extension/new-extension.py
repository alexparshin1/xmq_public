def class_name(name):
    """audit-trail -> AuditTrail."""
    return "".join(part.capitalize() for part in re.split(r"[-_\s]+", name) if part)


def identifier(name):
    """audit-trail -> audit_trail, for file and target names."""
    return re.sub(r"[-\s]+", "_", name)


def check_name(name):
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]*", name):
        raise SystemExit(
            "The name must start with a letter and hold only letters, digits, '-' and '_': "
            "it becomes a C++ class, a CMake target and the name the broker matches. Got: " + name)


